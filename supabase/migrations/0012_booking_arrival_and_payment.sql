-- Verification
-- ---------------------------------------------------------------------------

-- The five statuses, and the new constraints. Expect the widened status list
-- and three new CHECKs.
select conname, pg_get_constraintdef(oid) as definition
from pg_constraint
where conrelid = 'public.bookings'::regclass
  and conname in ('bookings_status_known', 'bookings_check_in_method_known',
                  'bookings_payment_method_known', 'bookings_reference_matches_payment')
order by conname;

-- Every function here must be SECURITY DEFINER with an empty search_path.
-- Expect prosecdef = true and proconfig = {search_path=} on all four.
select proname, prosecdef, proconfig
from pg_proc
where pronamespace = 'public'::regnamespace
  and proname in ('create_booking', 'settle_booking_payment',
                  'get_check_in_invite', 'check_in_booking')
order by proname;

-- Exactly one signature each — a leftover overload would make PostgREST pick
-- between them at random. Expect 1 row per name.
select proname, count(*) as signatures
from pg_proc
where pronamespace = 'public'::regnamespace
  and proname in ('create_booking', 'settle_booking_payment')
group by proname;

-- The seeded rows keep their NULLs; only bookings made through the app carry
-- the new facts. Expect 140 rows with everything null, until you book one.
select count(*) filter (where access_code is null)     as no_code,
       count(*) filter (where access_code is not null) as with_code,
       count(*) filter (where payment_method is null)  as no_method
from public.bookings;

